test("N6: a vendored provider (a path entry) is recorded with PATCHES.md's registry checksum and its tree digest; vendor/** and PATCHES.md are fixed inputs", (t) => {
  const f = fixture(t);
  put(f.binding, "Cargo.lock", vendoredLock());
  const m = reviewedInputs({ repo: f.repo, bindingRoot: f.binding });
  assert.deepEqual(m.library.crates.openmls, { version: "0.9.1", checksum: "a".repeat(64) }, "a registry crate as before");
  const tree = treeDigest(VENDORED.map(([p, c]) => [p.slice("vendor/openmls_libcrux_crypto/".length), c]));
  assert.deepEqual(m.library.crates.openmls_libcrux_crypto, { version: "0.4.0", source: "path", path: "vendor/openmls_libcrux_crypto", registryChecksum: "c".repeat(64), vendoredTree: tree });
  assert.deepEqual(m.library.vendored, { openmls_libcrux_crypto: { version: "0.4.0", path: "vendor/openmls_libcrux_crypto", registryChecksum: "c".repeat(64), vendoredTree: tree } });
  for (const [p, c] of [["vendor/PATCHES.md", PATCHES()], ...VENDORED]) assert.equal(m.library.files[`openmls-wasm/${p}`], sha256(c), p);
  // A change to the vendored source changes its file entry and the tree digest.
  put(f.binding, "vendor/openmls_libcrux_crypto/src/crypto.rs", "// patched differently\n");
  const m2 = reviewedInputs({ repo: f.repo, bindingRoot: f.binding });
  assert.notEqual(m2.library.crates.openmls_libcrux_crypto.vendoredTree, tree);
  assert.notEqual(m2.library.files["openmls-wasm/vendor/openmls_libcrux_crypto/src/crypto.rs"], m.library.files["openmls-wasm/vendor/openmls_libcrux_crypto/src/crypto.rs"]);
  put(f.binding, "vendor/openmls_libcrux_crypto/src/crypto.rs", "// patched\n");
  // Paths are sorted whole: a directory "src/a/" beside a file "src/a.txt" ("." sorts before "/").
  const extra = [["vendor/openmls_libcrux_crypto/src/a.txt", "file\n"], ["vendor/openmls_libcrux_crypto/src/a/b.rs", "nested\n"]];
  for (const [p, c] of extra) put(f.binding, p, c);
  const m3 = reviewedInputs({ repo: f.repo, bindingRoot: f.binding });
  assert.equal(m3.library.crates.openmls_libcrux_crypto.vendoredTree, treeDigest([...VENDORED, ...extra].map(([p, c]) => [p.slice("vendor/openmls_libcrux_crypto/".length), c])), "the digest follows sorted whole paths");
  for (const [p] of extra) fs.rmSync(path.join(f.binding, p), { recursive: true });
  fs.rmSync(path.join(f.binding, "vendor/openmls_libcrux_crypto/src/a"), { recursive: true });
  // Refusals: no record in PATCHES.md, another version, a malformed checksum, no vendored tree, a
  // path entry nobody vendored, PATCHES.md missing; a registry crate without a checksum still fails.
  const refuses = (lock, patches, re) => {
    put(f.binding, "Cargo.lock", lock);
    put(f.binding, "vendor/PATCHES.md", patches);
    assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), re);
  };
  refuses(vendoredLock(), PATCHES([["openmls_rust_crypto", "0.6.0", "d".repeat(64)]]), /openmls_libcrux_crypto is a path dependency without a registry checksum in vendor\/PATCHES\.md/);
  refuses(vendoredLock(), PATCHES([["openmls_libcrux_crypto", "0.4.1", "c".repeat(64)]]), /vendor\/PATCHES\.md records openmls_libcrux_crypto 0\.4\.1, the lock 0\.4\.0/);
  refuses(vendoredLock(), PATCHES([["openmls_libcrux_crypto", "0.4.0", "c".repeat(63)]]), /without a registry checksum/);
  refuses(vendoredLock(`\n[[package]]\nname = "stray"\nversion = "1.0.0"\n`), PATCHES(), /stray is a path dependency without a registry checksum/);
  put(f.binding, "Cargo.lock", vendoredLock());
  put(f.binding, "vendor/PATCHES.md", PATCHES());
  put(f.binding, "vendor/openmls_libcrux_crypto/Cargo.toml", '[package]\nname = "openmls_libcrux_crypto"\nversion = "0.4.2"\n');
  assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), /vendor\/openmls_libcrux_crypto\/Cargo\.toml is version 0\.4\.2, the lock 0\.4\.0/);
  fs.rmSync(path.join(f.binding, "vendor", "openmls_libcrux_crypto"), { recursive: true });
  assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), /openmls_libcrux_crypto: no vendored tree at vendor\/openmls_libcrux_crypto/);
  fs.rmSync(path.join(f.binding, "vendor"), { recursive: true });
  assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), /a listed path is missing: vendor\/PATCHES\.md/);
  assert.throws(() => lockedCrates(vendoredLock().replace(/checksum = "a+"\n/, ""), ["openmls"]), /openmls has no checksum/);
});

