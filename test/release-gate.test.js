// The release gate's records (design 3.5): the reviewed-input manifest, the runtime-artifact
// manifest and build mapping, and the release check over them. Fixture trees only: nothing here
// needs the bake-off or a network.
import { test } from "node:test";
import assert from "node:assert/strict";
import { spawnSync } from "node:child_process";
import crypto from "node:crypto";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { CLOSURE_EXCLUDED, DYNAMIC_LOADS, GROUPS, SHIPPED_EXCLUDED, buildMapping, canonical, declaredReviewedDigests, dockerfilePins, hoptellClosure, lockedCrates, recordsCheck, releaseCheck, reviewedInputs, runtimeArtifacts, shippedUnlisted, verifyBuildMapping } from "../scripts/gate-lib.mjs";

const sha256 = (b) => crypto.createHash("sha256").update(b).digest("hex");
const tmp = (t) => {
  const d = fs.mkdtempSync(path.join(os.tmpdir(), "hoptell-gate-"));
  t.after(() => fs.rmSync(d, { recursive: true, force: true }));
  return d;
};
const put = (base, rel, content) => {
  fs.mkdirSync(path.dirname(path.join(base, rel)), { recursive: true });
  fs.writeFileSync(path.join(base, rel), content);
};
const lockOf = (extra = "") => `# This file is automatically @generated by Cargo.
version = 4

[[package]]
name = "openmls"
version = "0.9.1"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${"a".repeat(64)}"
dependencies = [
 "serde",
]

[[package]]
name = "openmls_libcrux_crypto"
version = "0.4.0"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "${"b".repeat(64)}"
${extra}`;
// The vendored provider (design 3.5 group 1; bake-off vendor/PATCHES.md): a path entry in the lock
// (no source, no checksum), its crates.io checksum recorded in PATCHES.md, its tree under vendor/.
const PATCHES = (entries = [["openmls_libcrux_crypto", "0.4.0", "c".repeat(64)]]) =>
  `# Vendored crates: the advisory patch\n\nText.\n\n${entries.map(([n, v, c]) => `## ${n}\n\n- Published version: ${v} (crates.io checksum\n  \`${c}\`).\n- Upstream commit: e0b21a70a5.\n`).join("\n")}`;
const VENDORED = [
  ["vendor/openmls_libcrux_crypto/Cargo.toml", '[package]\nname = "openmls_libcrux_crypto"\nversion = "0.4.0"\n'],
  ["vendor/openmls_libcrux_crypto/src/crypto.rs", "// patched\n"],
];
/** The lock of a build whose provider is vendored: the root package and the provider as path entries. */
const vendoredLock = (extra = "") =>
  lockOf().replace(/name = "openmls_libcrux_crypto"\nversion = "0.4.0"\nsource = "[^"]*"\nchecksum = "b+"\n/, 'name = "openmls_libcrux_crypto"\nversion = "0.4.0"\ndependencies = [\n "hpke-rs",\n]\n') + `\n[[package]]\nname = "openmls-wasm"\nversion = "0.0.0"\ndependencies = [\n "openmls",\n]\n${extra}`;
/** The digest of a vendored tree as gate-lib records it: SHA-256 over "<sha256>  <path>\n" lines, paths sorted. */
const treeDigest = (files) => sha256(files.map(([p, c]) => [p, sha256(c)]).sort(([a], [b]) => (a < b ? -1 : 1)).map(([p, h]) => `${h}  ${p}\n`).join(""));

const DECL = (g, w) => `export const REVIEWED_BINDING = Object.freeze({ glue: ${g ? JSON.stringify(g) : "null"}, wasm: ${w ? JSON.stringify(w) : "null"} });\n`;
const GLUE = Buffer.from("exports.initSync = () => {};\n");
const WASM = Buffer.from([0, 0x61, 0x73, 0x6d, 1, 0, 0, 0]);
// The reproducible build's inputs (amendment A11): a Dockerfile pinning its images by digest, the
// toolchain pin, the image-build script and the glue wrapper.
const DOCKERFILE = `FROM --platform=linux/amd64 node:22.22.1-bookworm-slim@sha256:${"1".repeat(64)} AS node
FROM --platform=linux/amd64 rust:1.99.0-bookworm@sha256:${"2".repeat(64)}
RUN cargo install wasm-bindgen-cli --version 0.2.129 --locked --root /opt/wasm-bindgen
`;
const TOOLCHAIN = '[toolchain]\nchannel = "1.99.0"\n';
const IMAGE = `sha256:${"3".repeat(64)}`;
const OUTPUTS = { glue: sha256(GLUE), glueUnwrapped: sha256(Buffer.from("let wasm_bindgen;\n")), wasm: sha256(WASM) };
const attestation = (i, over = {}) => ({ image: IMAGE, started: `2026-10-11T0${i}:00:00Z`, finished: `2026-10-11T0${i}:05:00Z`, outputs: { ...OUTPUTS }, ...over });

/** A repository, a binding root and an unpacked package of a fixture reviewed build (files written in `order`). */
function fixture(t, { order = (xs) => xs, declared = [sha256(GLUE), sha256(WASM)] } = {}) {
  const base = tmp(t);
  const repo = path.join(base, "repo");
  const binding = path.join(base, "binding");
  const pkg = path.join(base, "package");
  const repoFiles = [
    ["lib/mls/openmls.js", `// adapter\n${DECL(...declared)}`],
    ["lib/mls/driver.js", "// driver\n"],
    ["lib/mls/sub/deep.js", "// a nested file\n"],
    // package.json is real JSON: the release check imports the package's lib/mls/openmls.js.
    ...GROUPS.hoptell.paths.filter((p) => !p.endsWith("/**")).map((p) => [p, p === "package.json" ? '{ "type": "module" }\n' : `// ${p}\n`]),
  ];
  for (const [p, c] of order(repoFiles)) put(repo, p, c);
  for (const [p, c] of order([
    ["Cargo.lock", lockOf()],
    ["Cargo.toml", '[package]\nname = "openmls-wasm"\n'],
    ["build.sh", "#!/bin/sh\n"],
    ["rust-toolchain.toml", TOOLCHAIN],
    ["src/lib.rs", "// binding\n"],
    ["src/b/mod.rs", "// more\n"],
    ["Dockerfile", DOCKERFILE],
    ["build-image.sh", "#!/bin/sh\n# image and build\n"],
    ["wrap-glue.mjs", "// the wrapper\n"],
    ["vendor/PATCHES.md", PATCHES()],
    ...VENDORED,
  ]))
    put(binding, p, c);
  for (const [p, c] of repoFiles) if (p !== "package-lock.json") put(pkg, p, c);
  put(pkg, "README.md", "not on the encrypted path (not under bin/ or lib/)\n");
  put(pkg, "lib/mls/binding/openmls_wasm.js", GLUE);
  put(pkg, "lib/mls/binding/openmls_wasm_bg.wasm", WASM);
  const records = { inputs: path.join(base, "rec", "reviewed-inputs.json"), runtime: path.join(base, "rec", "runtime-artifacts.json"), mapping: path.join(base, "rec", "build-mapping.json") };
  const inputsText = canonical(reviewedInputs({ repo, bindingRoot: binding }));
  put(base, "rec/reviewed-inputs.json", inputsText);
  put(base, "rec/runtime-artifacts.json", canonical(runtimeArtifacts(pkg)));
  put(base, "rec/build-mapping.json", canonical(buildMapping({ inputsBytes: Buffer.from(inputsText), dockerfile: DOCKERFILE, cargoLock: lockOf(), toolchainToml: TOOLCHAIN, imageId: IMAGE, glue: GLUE, wasm: WASM, attestations: [attestation(1), attestation(2)] })));
  return {
    base,
    repo,
    binding,
    pkg,
    records,
    check: () => releaseCheck({ pkgDir: pkg, repo, bindingRoot: binding, records }),
    strict: () => recordsCheck({ pkgDir: pkg, repo, bindingRoot: binding, records }).problems,
  };
}

test("reviewed-input manifest: the three groups, sorted and byte-identical whatever the order files were made in", (t) => {
  const a = fixture(t);
  const b = fixture(t, { order: (xs) => [...xs].reverse() });
  const ma = canonical(reviewedInputs({ repo: a.repo, bindingRoot: a.binding }));
  assert.equal(ma, canonical(reviewedInputs({ repo: b.repo, bindingRoot: b.binding })));
  assert.equal(ma, canonical(reviewedInputs({ repo: a.repo, bindingRoot: a.binding })));
  const m = JSON.parse(ma);
  assert.deepEqual(Object.keys(m), ["binding", "format", "hoptell", "library"]);
  assert.deepEqual(m.library.crates, { openmls: { version: "0.9.1", checksum: "a".repeat(64) }, openmls_libcrux_crypto: { version: "0.4.0", checksum: "b".repeat(64) } });
  assert.deepEqual(Object.keys(m.library.files), ["openmls-wasm/Cargo.lock", "openmls-wasm/vendor/PATCHES.md", ...VENDORED.map(([p]) => `openmls-wasm/${p}`)]);
  assert.equal(m.format, "hoptell-reviewed-inputs-2");
  assert.deepEqual(Object.keys(m.binding.files), ["openmls-wasm/Cargo.toml", "openmls-wasm/Dockerfile", "openmls-wasm/build-image.sh", "openmls-wasm/build.sh", "openmls-wasm/rust-toolchain.toml", "openmls-wasm/src/b/mod.rs", "openmls-wasm/src/lib.rs", "openmls-wasm/wrap-glue.mjs"]);
  assert.equal(m.binding.files["openmls-wasm/Dockerfile"], sha256(DOCKERFILE));
  const keys = Object.keys(m.hoptell.files);
  assert.deepEqual(keys, [...keys].sort());
  for (const p of ["lib/mls/sub/deep.js", "lib/relaystore.js", "package-lock.json", "package.json"]) assert.ok(keys.includes(p), p);
  assert.ok(!ma.includes(a.base), "no absolute path is recorded");
});

test("reviewed-input manifest: a new file under a listed directory is in scope; a missing listed path, or a symlink, fails clearly", (t) => {
  const f = fixture(t);
  put(f.repo, "lib/mls/new.js", "// new\n");
  assert.ok(reviewedInputs({ repo: f.repo, bindingRoot: f.binding }).hoptell.files["lib/mls/new.js"]);
  // A11: the Dockerfile, the image-build script and the wrapper are listed by name.
  for (const name of ["Dockerfile", "build-image.sh", "wrap-glue.mjs"]) {
    const c = fs.readFileSync(path.join(f.binding, name));
    fs.rmSync(path.join(f.binding, name));
    assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), new RegExp(`a listed path is missing: ${name.replace(".", "\\.")} \\(under the binding root `));
    put(f.binding, name, c);
  }
  assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: path.join(f.base, "nowhere") }), /a listed path is missing: Cargo\.lock/);
  fs.rmSync(path.join(f.repo, "lib", "inbox.js"));
  assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), /a listed path is missing: lib\/inbox\.js \(under the repository\)/);
  put(f.repo, "lib/inbox.js", "//\n");
  fs.symlinkSync(path.join(f.repo, "lib", "inbox.js"), path.join(f.repo, "lib", "mls", "link.js"));
  assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), /lib\/mls\/link\.js: a symbolic link/);
});

test("group 3 covers its import closure: every module the encrypted path loads is listed or excluded with a reason", () => {
  const { closure, unlisted, dynamic } = hoptellClosure();
  assert.deepEqual(unlisted, [], "add these to GROUPS.hoptell.paths, or to CLOSURE_EXCLUDED with a reason");
  assert.deepEqual(dynamic, [], "a load the static closure cannot follow: name it in DYNAMIC_LOADS with a reason");
  for (const f of ["lib/contacts.js", "lib/reviewsets.js", "lib/claims.js", "lib/credentials.js", "lib/locks.js"]) assert.ok(closure.includes(f), f);
  // N7 (3.5 preparation): files that change encrypted-path state, or decide it, are entry points.
  for (const f of ["lib/restore.js", "lib/admin.js", "lib/admincli.js", "bin/hoptell.js", "lib/ownerui.js"]) assert.ok(closure.includes(f), `${f} is in group 3`);
  for (const [f, why] of Object.entries(CLOSURE_EXCLUDED)) {
    assert.ok(closure.includes(f), `${f} is excluded but no longer in the closure`);
    assert.ok(typeof why === "string" && why.length > 10, `${f} needs a reason`);
  }
  // Every named dynamic load still exists (no stale entry hides a new one).
  for (const [f, loads] of Object.entries(DYNAMIC_LOADS)) {
    const src = fs.readFileSync(f, "utf8").replace(/\s+/g, "");
    for (const load of Object.keys(loads)) assert.ok(src.includes(load), `${f}: ${load} is gone`);
  }
});

test("group 3's closure in a fixture: a new unlisted import, a non-literal load or a missing module fails the manifest", (t) => {
  const f = fixture(t);
  assert.deepEqual(hoptellClosure(f.repo).unlisted, []);
  put(f.repo, "lib/helper.js", "export const x = 1;\n");
  put(f.repo, "lib/mls/sub/deep.js", 'import { x } from "../../helper.js";\n');
  assert.deepEqual(hoptellClosure(f.repo).unlisted, ["lib/helper.js"]);
  assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), /import closure has files neither listed nor excluded: lib\/helper\.js/);
  // Transitively, through a listed file, and through export ... from and import().
  put(f.repo, "lib/mls/sub/deep.js", "// none\n");
  put(f.repo, "lib/engine.js", 'export * from "./helper.js";\n');
  assert.deepEqual(hoptellClosure(f.repo).unlisted, ["lib/helper.js"]);
  put(f.repo, "lib/engine.js", 'const m = await import("./helper.js");\n');
  put(f.repo, "lib/helper.js", 'import "./helper2.js";\n');
  put(f.repo, "lib/helper2.js", "//\n");
  assert.deepEqual(hoptellClosure(f.repo).unlisted, ["lib/helper.js", "lib/helper2.js"]);
  put(f.repo, "lib/engine.js", "const m = await import(path.join(dir, name));\n");
  assert.deepEqual(hoptellClosure(f.repo).dynamic, [{ file: "lib/engine.js", load: "import(path.join(dir,name))" }]);
  assert.throws(() => reviewedInputs({ repo: f.repo, bindingRoot: f.binding }), /non-literal loads the closure cannot follow: lib\/engine\.js: import\(path\.join\(dir,name\)\)/);
  put(f.repo, "lib/engine.js", 'import "./gone.js";\n');
  assert.throws(() => hoptellClosure(f.repo), /lib\/engine\.js: loads \.\/gone\.js, which is no file of the repository/);
});

